#include "libft.h"

size_t	ft_strlcpy(char *dst, const char *src, size_t size)
{
	size_t	i;
	size_t	sz;

	i = 0;
	sz = 0;
	while (src[sz])
		sz++;
	if (size == 0)
		return (sz);
	while ((i < size - 1) && src[i])
	{
		dst[i] = src[i];
		i++;
	}
	dst[i] = '\0';
	return (sz);
}
